#!/usr/bin/env python3
"""build_cantilever_inp.py -- plane-strain cantilever decks for S1 tests 3-4 (CPE4I vs tslid.fe).

Units: mm, N, MPa.  Python 3.6+, stdlib only (runs on the cluster's system python3).

Beam [0, L] x [0, H], out-of-plane thickness W, Al: E = 70000, nu = 0.33.  Left edge
(x = 0) clamped: U1 = U2 = 0 on every node.  Right edge (x = L):
    --load force : uniform shear traction, total --P (N) in +y, as consistent nodal forces
                   (dead load; same nodal values as tslid.fe.meshing.edge_load)
    --load disp  : every right-edge node U2 = --v (mm), U1 free
Mesh identical to tslid.fe.meshing.beam (same graded()/uniform(), node id = i*(ny+1)+j+1).
Nonlinear decks (--nlgeom YES) use --n-inc fixed equal increments and tight equilibrium
tolerances so every increment is a converged point of the load path.

    python3 scripts/fe/build_cantilever_inp.py --job lin_ny20_F --ny 20 --load force --P 230
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src'))
from tslid.build_tpeel_inp import graded, uniform, git_rev  # noqa: E402


def parse(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a = p.add_argument
    a('--job', required=True)
    a('--outdir', default='.')
    a('--L', type=float, default=60.0)
    a('--H', type=float, default=6.324)
    a('--W', type=float, default=15.0)
    a('--hx', type=float, default=0.1)
    a('--ny', type=int, default=20)
    a('--h-y0', type=float, default=0.1, help='first element height at y = 0; <= 0 for uniform')
    a('--skew', type=float, default=0.0, help='alternate-row x shift of interior nodes, mm')
    a('--E', type=float, default=70000.0)
    a('--nu', type=float, default=0.33)
    a('--eltype', default='CPE4I')
    a('--load', choices=['force', 'disp'], default='force')
    a('--P', type=float, default=230.0, help='total tip force, N (force control)')
    a('--v', type=float, default=0.67, help='tip displacement, mm (displacement control)')
    a('--nlgeom', choices=['YES', 'NO'], default='NO')
    a('--n-inc', type=int, default=1)
    return p.parse_args(argv)


def mesh(o):
    xs = uniform(0.0, o.L, o.hx)
    ys = graded(o.H, o.ny, o.h_y0) if o.h_y0 > 0 else uniform(0.0, o.H, o.H / o.ny)
    nx, ny = len(xs) - 1, o.ny
    nid = lambda i, j: i * (ny + 1) + j + 1
    nodes = {}
    for i, x in enumerate(xs):
        for j, y in enumerate(ys):
            dx = 0.0
            if o.skew and 0 < i < nx:
                dx = o.skew if j % 2 == 0 else -o.skew
            nodes[nid(i, j)] = (x + dx, y)
    els = [(i * ny + j + 1, [nid(i, j), nid(i + 1, j), nid(i + 1, j + 1), nid(i, j + 1)])
           for i in range(nx) for j in range(ny)]
    left = [nid(0, j) for j in range(ny + 1)]
    right = [nid(nx, j) for j in range(ny + 1)]
    return nodes, els, left, right, ys


def edge_load(ys, total):
    f = [0.0] * len(ys)
    for k in range(len(ys) - 1):
        s = (ys[k + 1] - ys[k]) / (ys[-1] - ys[0]) * total
        f[k] += 0.5 * s
        f[k + 1] += 0.5 * s
    return f


def ids(v, per=16):
    return '\n'.join(', '.join(str(x) for x in v[k:k + per]) for k in range(0, len(v), per))


def write(o):
    nodes, els, left, right, ys = mesh(o)
    L = ['*Heading', 'S1 cantilever %s | %s ny=%d hx=%g load=%s nlgeom=%s' %
         (o.job, o.eltype, o.ny, o.hx, o.load, o.nlgeom),
         '** generated by scripts/fe/build_cantilever_inp.py @ %s' % git_rev()]
    for k, v in sorted(vars(o).items()):
        L.append('** param %s = %s' % (k, v))
    L.append('*Preprint, echo=NO, model=NO, history=NO, contact=NO')
    L.append('*Node')
    L += ['%d, %.15g, %.15g' % (n, x, y) for n, (x, y) in sorted(nodes.items())]
    L.append('*Element, type=%s, elset=BEAM' % o.eltype)
    L += ['%d, %s' % (e, ', '.join(str(n) for n in c)) for e, c in els]
    L += ['*Nset, nset=LEFT', ids(left), '*Nset, nset=RIGHT', ids(right)]
    L += ['*Solid Section, elset=BEAM, material=AL', '%.15g,' % o.W,
          '*Material, name=AL', '*Elastic', '%.15g, %.15g' % (o.E, o.nu),
          '*Boundary', 'LEFT, 1, 2']
    L.append('*Step, name=LOAD, nlgeom=%s, inc=1000' % o.nlgeom)
    if o.nlgeom == 'YES':
        L += ['*Static, direct', '%.15g, 1.0' % (1.0 / o.n_inc),
              '*Controls, parameters=field, field=displacement', '1e-8, 1e-8']
    else:
        L += ['*Static', '1.0, 1.0']
    if o.load == 'force':
        L.append('*Cload')
        L += ['%d, 2, %.15g' % (n, f) for n, f in zip(right, edge_load(ys, o.P))]
    else:
        L += ['*Boundary', 'RIGHT, 2, 2, %.15g' % o.v]
    L += ['*Output, field, frequency=1', '*Node Output', 'U, RF', '*End Step']
    os.makedirs(o.outdir, exist_ok=True)
    path = os.path.join(o.outdir, o.job + '.inp')
    with open(path, 'w') as f:
        f.write('\n'.join(L) + '\n')
    with open(os.path.join(o.outdir, o.job + '.json'), 'w') as f:
        json.dump(dict(params=vars(o), n_nodes=len(nodes), n_elems=len(els), git=git_rev()),
                  f, indent=2, sort_keys=True)
    return path, len(nodes), len(els)


if __name__ == '__main__':
    o = parse()
    print('wrote %s (%d nodes, %d elements)' % write(o))
